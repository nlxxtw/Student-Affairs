"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const source = fs.readFileSync(path.join(__dirname, "..", "dorm-spatial-module.js"), "utf8");
let failSave = false, wizard, template;
const store = new Map();
const context = {
  window: {}, students: [], ORG_DORMS: [], saveOrgs() {}, showToast() {}, reportDataError() {},
  localStorage: { getItem: k => store.get(k) || null, setItem(k, v) { if (failSave) { failSave = false; throw Error("disk full"); } store.set(k, v); }, removeItem: k => store.delete(k) },
  openMappedImportWizard: value => { wizard = value; }, downloadXlsxFile: (...args) => { template = args; }
};
vm.createContext(context); vm.runInContext(source, context);
(async () => {
const api = context.window.__DORM_SPATIAL__;
assert.strictEqual(typeof context.window.dormSpatialImportBuildings, "function");
context.window.dormSpatialImportBuildings();
const building = { "区位": "北区", "宿舍楼": "A栋" };
assert.strictEqual(wizard.validate([building]).errors.length, 0);
assert.strictEqual((await wizard.apply([building])).ok, 1);
assert.strictEqual((await wizard.apply([building])).skip, 1);
const buildingDuplicates=wizard.validate([building, building]);
assert.strictEqual(buildingDuplicates.ok.length, 1);
assert.strictEqual(buildingDuplicates.errors.length, 0);
assert.strictEqual(buildingDuplicates.duplicates, 1);
assert.match(buildingDuplicates.warnings[0].msg, /重复.*去重/);
assert.match(wizard.validate([{ ...building, "区位": "南区" }]).errors[0].msg, /区位/);
assert.strictEqual((await wizard.apply([{ "区位": "北区", "宿舍楼": "B栋" }, { "宿舍楼": "C栋" }])).failed, true);
assert.strictEqual(api.getState().buildings.length, 1, "invalid batch must not partially write");
context.window.dormSpatialBuildingTemplate();
assert.deepStrictEqual(Array.from(template[1][0]), ["区位", "宿舍楼"]);
context.window.dormSpatialImportRooms();
const room = { ...building, "楼层": "1", "宿舍号": "0101", "床位数": "2" };
assert.strictEqual((await wizard.apply([room])).ok, 1);
const id = api.getState().rooms[0].id;
assert.strictEqual(api.getState().rooms[0].bedCount, 2, "capacity must match input even below default");
assert.strictEqual(api.getState().rooms[0].room, "0101");
assert.strictEqual((await wizard.apply([room])).skip, 1);
assert.strictEqual((await wizard.apply([{ ...room, "床位数": "6" }])).ok, 1);
assert.strictEqual(api.getState().rooms[0].id, id, "updates preserve room identity");
for (const value of ["", "0", "1.5", "31", "abc"]) assert.strictEqual(wizard.validate([{ ...room, "床位数": value }]).ok.length, 0);
assert.strictEqual(wizard.validate([{ ...room, "楼层": "2" }]).ok.length, 0);
const roomDuplicates=wizard.validate([room, room]);
assert.strictEqual(roomDuplicates.ok.length, 1);
assert.strictEqual(roomDuplicates.errors.length, 0);
assert.strictEqual(roomDuplicates.duplicates, 1);
const currentRoom={...room,"床位数":"6"};
const identicalResult=await wizard.apply([currentRoom,currentRoom]);
assert.strictEqual(identicalResult.skip, 2, "one identical database row plus one file duplicate are skipped");
assert.strictEqual(identicalResult.duplicates, 1);
assert.match(wizard.validate([room,{...room,"床位数":"8"}]).errors[0].msg,/冲突/);
assert.match(wizard.validate([room,{...room,"楼层":"9"}]).errors[0].msg,/冲突|楼层/);
const snapshot = api.getState();
snapshot.bedNotes.push({ id: "note", roomId: id, bedNo: "6", studentName: "登记人" });
api.restoreState(snapshot);
assert.match(wizard.validate([room]).errors[0].msg, /登记/);
snapshot.bedNotes=[];
snapshot.assignments.push({ id: "planned", roomId: id, studentId: "future", bedNo: "6", status: "planned" });
api.restoreState(snapshot);
assert.match(wizard.validate([room]).errors[0].msg, /已计划/);
context.window.__WORKBENCH_READ_ONLY__=true;
assert.strictEqual((await wizard.apply([{ ...room, "床位数": "8" }])).failed, true);
assert.strictEqual(api.getState().rooms[0].bedCount, 6);
context.window.__WORKBENCH_READ_ONLY__=false;
const before = JSON.stringify(api.getState());
failSave = true;
assert.strictEqual((await wizard.apply([{ ...room, "宿舍楼": "新楼", "宿舍号": "102", "床位数": "4" }])).failed, true);
assert.strictEqual(JSON.stringify(api.getState()), before, "failed save restores memory");
api.reloadState();
assert.strictEqual(JSON.stringify(api.getState()), before, "failed save restores persisted data");
context.window.dormSpatialRoomTemplate();
assert.deepStrictEqual(Array.from(template[1][0]), ["区位", "宿舍楼", "楼层", "宿舍号", "床位数"]);
console.log("Dorm resource import validation, idempotency, capacity and rollback passed.");
})().catch(error => { console.error(error); process.exitCode = 1; });
